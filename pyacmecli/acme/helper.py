"""Compatibility facade for code written against pyacme < 0.2.0.

The implementation now lives in:

- pyacmecli.acme.client: ACME protocol, JWS and AcmeClient
- pyacmecli.acme.storage: files under the pyacme home directory
- pyacmecli.acme.dnscheck: DNS propagation checks
- pyacmecli.acme.operations: issue, renew, revoke, inspect, export

Importing a name from here keeps working. Patching one here does not affect
the code that uses it: patch the defining module instead (for example
pyacmecli.acme.storage.PYACME_HOME_PATH to relocate the store).
"""

